// ACORDAJ 3.0.0 — acordor cu temperamente istorice (justă, meantone, pitagoreic, Werckmeister III).
import {createRequire} from 'module';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const require = createRequire(process.env.PW_ROOT || import.meta.url);
const {chromium} = require('playwright');
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
let pass = 0, fail = 0;
const ok = (c, n, i) => { if (c) { pass++; console.log('  ok   ' + n); } else { fail++; console.log('  FAIL ' + n + (i === undefined ? '' : ' ' + JSON.stringify(i).slice(0, 300))); } };
const browser = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--no-sandbox']});
const ctx = await browser.newContext({viewport: {width: 1280, height: 800}, locale: 'ro-RO'});
const page = await ctx.newPage();
const errs = [], reqs = [];
await ctx.route(/^https?:/, r => { reqs.push(r.request().url()); r.abort(); });
page.on('pageerror', e => errs.push(e.message));
await page.goto('file://' + ROOT + '/index.html');
await page.waitForTimeout(1500);
await page.evaluate(() => { const m = document.getElementById('modal'); if (m) m.remove(); });
await page.evaluate(() => document.querySelector('#nav button[data-v="temp"]').click());
await page.waitForSelector('#tempBox table');
const rows = async () => page.$$eval('#tempBox tbody tr', r => r.map(x => ({pc: +x.dataset.pc, dev: +x.dataset.dev, hz: +x.dataset.hz})));
const pick = async id => { await page.selectOption('#tmSel', id); await page.waitForSelector('#tmSel'); return rows(); };
console.log('1. tabel și valori');
let R = await rows();
ok(R.length === 12, '12 note');
ok(Math.abs(R[9].hz - 440) < 1e-6 && Math.abs(R[9].dev) < 1e-6, 'La4 = 440 Hz, abatere 0 (ancoră)', R[9]);
// intonația justă: terța mare Do-Mi = 386.31 cenți => față de La: abatere Mi = (386.31-884.36) - (400-900) = ...
R = await pick('just');
const expMi = (1200 * Math.log2(5 / 4) - 1200 * Math.log2(5 / 3)) - (400 - 900);
ok(Math.abs(R[4].dev - expMi) < 0.02, 'justă: abaterea Mi corectă', [R[4].dev, expMi]);
R = await pick('et');
ok(R.every(x => Math.abs(x.dev) < 1e-6), 'egal temperat: toate abaterile 0');
R = await pick('werck');
ok(Math.abs(R[0].dev - ((0 - 888.27) + 900)) < 0.05, 'Werckmeister III: Do față de La ≈ +11.7', R[0]);
const iv = async () => page.$eval('#tmIv', e => ({maj3: +e.dataset.maj3, min3: +e.dataset.min3, p5: +e.dataset.p5}));
let I = await iv();
ok(Math.abs(I.p5 - 696.09) < 0.05, 'Werckmeister: cvinta Do-Sol ≈ 696.09', I);
ok(Math.abs(I.maj3 - 390.225) < 0.05, 'Werckmeister: terța Do-Mi ≈ 390.23', I);
R = await pick('mean');
I = await iv();
ok(Math.abs(I.maj3 - 386.314) < 0.01, 'meantone: terța mare pură 386.31', I);
ok(Math.abs(I.p5 - 696.578) < 0.01, 'meantone: cvinta 696.58', I);
R = await pick('pyth');
I = await iv();
ok(Math.abs(I.p5 - 701.955) < 0.01, 'pitagoreic: cvinta pură', I);
ok(Math.abs(I.maj3 - 407.82) < 0.02, 'pitagoreic: terța mare 407.82', I);
await page.selectOption('#tmRoot', '8');
I = await iv();
ok(I.p5 < 701.9 - 20 || I.p5 > 701.9 + 20, 'pitagoreic: cvinta lupului pe Sol♯ diferă mult de 701.96', I);
console.log('2. La4 și redare');
await page.fill('#tmA4', '415'); await page.dispatchEvent('#tmA4', 'change');
R = await rows();
ok(Math.abs(R[9].hz - 415) < 1e-6, 'La4 = 415 Hz', R[9]);
await page.click('#tmMaj');
ok(/acordul major/.test(await page.textContent('#tmSt')), 'redare acord major');
await page.click('.tmN[data-pc="0"]');
ok(/Hz/.test(await page.textContent('#tmSt')), 'redare notă');
await page.click('#tmCmp');
ok(/egal temperat/.test(await page.textContent('#tmSt')), 'comparație');
await page.click('#tmStop');
ok(/Oprit/.test(await page.textContent('#tmSt')), 'oprire');
console.log('3. general');
ok(await page.$eval('#tempBox svg', s => !!s.getAttribute('aria-label')), 'svg cu aria-label');
ok(await page.$eval('#tempBox', e => /educațional/.test(e.textContent)), 'avertisment educațional');
ok(errs.length === 0, '0 erori JS', errs);
ok(reqs.length === 0, '0 cereri de rețea', reqs);
await browser.close();
console.log(`\n${pass} reușite, ${fail} eșuate`);
process.exit(fail ? 1 : 0);
